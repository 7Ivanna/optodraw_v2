def __getattr__(name: str):
    if name in _LAZY_GDS_XSECTION_EXPORTS:
        from optodraw import gds

        value = getattr(gds, name)
        globals()[name] = value
        return value
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")

