"""optodraw: optical setup diagrams in 1D, 2D, 3D, and animation.

Usage::

    from optodraw import Scene, Laser, Mirror, Lens, Beam

    scene = Scene()
    las = scene.add(Laser(center=(0, 0), angle=0, wavelength=532))
    mir = scene.add(Mirror(center=(30, 0), angle=45))
    lens = scene.add(Lens(center=(30, 30), angle=90))
    scene.add(Beam(las, mir, lens))

    # Render to SVG
    scene.render_svg("setup.svg", width=200, height=100)

    # Render to interactive 3D (opens browser)
    scene.render_threejs("setup.html")

    # Render to video
    scene.render_video("setup.mp4")
"""

